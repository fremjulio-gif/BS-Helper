/**
 * Retourne le nom officiel en Français d'un brawler, à partir de son nom ou de son ID.
 */
export function getBrawlerFrenchName(name?: string | null, id?: number): string {
  if (id && BRAWLER_ID_TO_FR[id]) {
    return BRAWLER_ID_TO_FR[id];
  }
  if (!name) return 'Brawler';
  const clean = name.trim().toUpperCase();
  if (BRAWLER_FRENCH_NAMES[clean]) {
    return BRAWLER_FRENCH_NAMES[clean];
  }
  // Title Case propre si pas de mapping spécifique
  return clean.charAt(0) + clean.slice(1).toLowerCase();
}
